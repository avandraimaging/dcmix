defmodule Dcmix.UID do
  @moduledoc """
  dcmix's own UIDs, all under the root Medical Connections assigned to
  Avandra Imaging, `1.2.826.0.1.3680043.10.1712`.

  The arcs under the root:

  - `.1` - the Implementation Class UID dcmix identifies itself with, in
    association requests and in written files' meta header
  - `.1.1` - UIDs generated by `generate/0`, kept apart from the values we
    choose ourselves so they can't collide
  """

  @root "1.2.826.0.1.3680043.10.1712"
  @implementation_class_uid @root <> ".1"
  @generated_root @implementation_class_uid <> ".1"
  @implementation_version_name "DCMIX_" <> Mix.Project.config()[:version]

  # Largest random arc that keeps a generated UID within 64 characters
  @max_random 999_999_999_999_999

  @doc """
  The root UID assigned to Avandra Imaging.

      iex> Dcmix.UID.root()
      "1.2.826.0.1.3680043.10.1712"
  """
  @spec root() :: String.t()
  def root, do: @root

  @doc """
  dcmix's Implementation Class UID (0002,0012), the root plus `.1`.

      iex> Dcmix.UID.implementation_class_uid()
      "1.2.826.0.1.3680043.10.1712.1"
  """
  @spec implementation_class_uid() :: String.t()
  def implementation_class_uid, do: @implementation_class_uid

  @doc """
  dcmix's Implementation Version Name (0002,0013), `DCMIX_` plus the
  library version.

      iex> Dcmix.UID.implementation_version_name() == "DCMIX_" <> to_string(Application.spec(:dcmix, :vsn))
      true
  """
  @spec implementation_version_name() :: String.t()
  def implementation_version_name, do: @implementation_version_name

  @doc """
  Generates a new UID: the root plus `.1.1`, then the UTC date, time and a
  random number, e.g. `1.2.826.0.1.3680043.10.1712.1.1.20240115.93456.48213977`.

  The time drops its leading zeros, since a UID component can't have any
  (PS3.5 9.1).

      iex> Dcmix.UID.generate() |> String.starts_with?("1.2.826.0.1.3680043.10.1712.1.1.")
      true
  """
  @spec generate() :: String.t()
  def generate do
    now = DateTime.utc_now()

    Enum.join(
      [
        @generated_root,
        Calendar.strftime(now, "%Y%m%d"),
        String.to_integer(Calendar.strftime(now, "%H%M%S")),
        :rand.uniform(@max_random)
      ],
      "."
    )
  end
end
